#!/usr/bin/env python3
"""Pack Chakan's nonempty 8x8 tiles and animation SAT entries, no dependencies."""
import argparse
from pathlib import Path
from convert_test_level import ROOT, read_png


def generate():
    width, height, rows, palette = read_png(ROOT / 'res/sprites/Chakan/chakan_anim_no_weapons.png')
    if (width, height) != (896, 400):
        raise ValueError('expected five 112x80 animation rows, eight columns')
    tiles, lookup, frames, offsets = [], {}, [], [0]
    for animation in range(5):
        for frame in range(8 if animation == 1 else 1):
            entries = []
            for ty in range(10):
                for tx in range(14):
                    tile = tuple(rows[animation * 80 + ty * 8 + y][frame * 112 + tx * 8 + x]
                                 for y in range(8) for x in range(8))
                    if not any(tile):
                        continue
                    if tile not in lookup:
                        lookup[tile] = len(tiles)
                        tiles.append(tile)
                    entries.append((tx * 8, ty * 8, lookup[tile]))
            if len(entries) > 80:
                raise ValueError('frame exceeds Genesis sprite limit')
            for scanline in range(80):
                if sum(y <= scanline < y + 8 for x, y, t in entries) > 20:
                    raise ValueError('frame exceeds H40 scanline sprite limit')
            frames.extend(entries)
            offsets.append(len(frames))
    # Separate fixed VRAM allocation, beyond the test level's indices 16..180.
    base = 192
    if base + len(tiles) > 0x8000 // 32:
        raise ValueError('sprite patterns overlap plane A')
    out = ['/* Generated by md_src/tools/convert_sprites.py. */',
           f'#define CHAKAN_TILE_BASE {base}', f'#define CHAKAN_TILE_COUNT {len(tiles)}',
           'static const uint16_t chakan_palette[] = {',
           ', '.join(f'0x{x:04X}' for x in palette), '};',
           'static const uint16_t chakan_tiles[] = {']
    for tile in tiles:
        words = [(tile[i] << 12) | (tile[i + 1] << 8) | (tile[i + 2] << 4) | tile[i + 3]
                 for i in range(0, 64, 4)]
        out.append(', '.join(f'0x{x:04X}' for x in words) + ',')
    out.extend(['};', 'static const uint16_t chakan_frame_offsets[] = {',
                ', '.join(map(str, offsets)), '};',
                'static const struct { uint16_t x, y, tile; } chakan_pieces[] = {'])
    out.extend(f'{{{x}, {y}, {tile}}},' for x, y, tile in frames)
    out.append('};')
    print(f'Chakan: {len(offsets) - 1} frames, {len(tiles)} unique tiles')
    return '\n'.join(out) + '\n'


if __name__ == '__main__':
    parser = argparse.ArgumentParser()
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    output = generate()
    target = ROOT / 'res/sprites.h'
    if args.check:
        if not target.exists() or target.read_text() != output:
            raise SystemExit('Sprite resources are stale; run make.')
    else:
        target.write_text(output)

#!/usr/bin/env python3
"""Convert the checked-in indexed PNGs to uncompressed Genesis resources.

Uses only Python's standard library. Rejects unsupported PNG formats rather
than silently quantizing source colors or losing palette banks.
"""
import argparse
import json
import struct
import zlib
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent


def read_png(path):
    data = path.read_bytes()
    if data[:8] != b'\x89PNG\r\n\x1a\n':
        raise ValueError(f'{path}: invalid PNG signature')
    pos, palette, compressed = 8, None, bytearray()
    while pos < len(data):
        size = struct.unpack_from('>I', data, pos)[0]
        kind = data[pos + 4:pos + 8]
        chunk = data[pos + 8:pos + 8 + size]
        crc = struct.unpack_from('>I', data, pos + 8 + size)[0]
        if zlib.crc32(kind + chunk) & 0xffffffff != crc:
            raise ValueError(f'{path}: corrupt {kind!r} chunk')
        if kind == b'IHDR':
            width, height, depth, color, compression, filtering, interlace = struct.unpack('>IIBBBBB', chunk)
            if (depth, color, compression, filtering, interlace) != (8, 3, 0, 0, 0):
                raise ValueError(f'{path}: expected noninterlaced 8-bit indexed PNG')
        elif kind == b'PLTE':
            palette = list(zip(chunk[::3], chunk[1::3], chunk[2::3]))
        elif kind == b'IDAT':
            compressed.extend(chunk)
        elif kind == b'IEND':
            break
        pos += size + 12
    if width % 8 or height % 8 or palette is None:
        raise ValueError(f'{path}: invalid tile dimensions or missing palette')
    raw = zlib.decompress(compressed)
    if len(raw) != (width + 1) * height:
        raise ValueError(f'{path}: unexpected decoded size')
    rows, previous = [], [0] * width
    for y in range(height):
        offset = y * (width + 1)
        filter_type = raw[offset]
        row = list(raw[offset + 1:offset + 1 + width])
        if filter_type > 4:
            raise ValueError(f'{path}: invalid PNG filter')
        for x in range(width):
            left = row[x - 1] if x else 0
            above = previous[x]
            corner = previous[x - 1] if x else 0
            p = left + above - corner
            distances = (abs(p - left), abs(p - above), abs(p - corner))
            paeth = (left, above, corner)[distances.index(min(distances))]
            predictor = (0, left, above, (left + above) // 2, paeth)[filter_type]
            row[x] = (row[x] + predictor) & 255
        rows.append(row)
        previous = row
    if max(max(row) for row in rows) >= min(16, len(palette)):
        raise ValueError(f'{path}: this slice requires one 16-color palette')
    colors = [(b >> 5) << 9 | (g >> 5) << 5 | (r >> 5) << 1 for r, g, b in palette[:16]]
    return width, height, rows, colors + [0] * (16 - len(colors))


def convert(path):
    width, height, rows, colors = read_png(path)
    tiles, lookup, tilemap = [], {}, []
    for ty in range(0, height, 8):
        for tx in range(0, width, 8):
            tile = tuple(rows[ty + y][tx + x] << 4 | rows[ty + y][tx + x + 1]
                         for y in range(8) for x in range(0, 8, 2))
            if tile not in lookup:
                lookup[tile] = len(tiles)
                tiles.append(tile)
            tilemap.append(lookup[tile])
    words = [(tile[i] << 8) | tile[i + 1] for tile in tiles for i in range(0, 32, 2)]
    return width // 8, height // 8, tiles, words, tilemap, colors


def generate():
    output = ['/* Generated by md_src/tools/convert_test_level.py; do not edit. */']
    base = 16  # Reserve prototype tiles 0..15, including its player and indicators.
    for name, filename in [('level_fg', 'fg_test_level.png'), ('level_bg', 'portal_starfield.png')]:
        width, height, tiles, words, tilemap, colors = convert(ROOT / 'res/levels/Hub' / filename)
        if base + len(tiles) > 0x8000 // 32:
            raise ValueError('tile patterns overlap plane A')
        output.extend([f'#define {name.upper()}_BASE {base}',
                       f'#define {name.upper()}_COUNT {len(tiles)}',
                       f'#define {name.upper()}_WIDTH {width}',
                       f'#define {name.upper()}_HEIGHT {height}'])
        for suffix, values in [('palette', colors), ('tiles', words), ('map', tilemap)]:
            output.append(f'static const uint16_t {name}_{suffix}[] = {{')
            for i in range(0, len(values), 12):
                output.append('    ' + ', '.join(f'0x{v:04X}' for v in values[i:i + 12]) + ',')
            output.append('};')
        print(f'{filename}: {width}x{height} map, {len(tiles)} unique tiles, base {base}')
        base += len(tiles)
    if base > 192:
        raise ValueError('level tiles overlap reserved Chakan tiles at index 192')
    collision = json.loads((ROOT / 'src/levels/test/test_small_collision.json').read_text())
    if (collision['width'], collision['height'], collision['cell_size']) != (20, 15, 16):
        raise ValueError('unexpected collision dimensions')
    grid = []
    for row in collision['rows_rle']:
        cells = []
        for run in row:
            tile_id, count = run >> 8, run & 255
            if tile_id not in (0, 1) or count == 0:
                raise ValueError('unsupported collision ID or empty run')
            cells.extend([tile_id] * count)
        if len(cells) != collision['width']:
            raise ValueError('collision row width mismatch')
        grid.extend(cells)
    if len(grid) != collision['width'] * collision['height']:
        raise ValueError('collision height mismatch')
    output.append('static const uint8_t level_collision[] = {')
    for i in range(0, len(grid), 20):
        output.append('    ' + ', '.join(map(str, grid[i:i + 20])) + ',')
    output.append('};')
    output.append(f"#define LEVEL_SPAWN_X {collision['spawn'][0]}")
    output.append(f"#define LEVEL_SPAWN_Y {collision['spawn'][1]}")
    return '\n'.join(output) + '\n' 


if __name__ == '__main__':
    parser = argparse.ArgumentParser()
    parser.add_argument('--check', action='store_true', help='verify generated output is current')
    args = parser.parse_args()
    generated = generate()
    target = ROOT / 'res/test_small_data.h'
    if args.check:
        if not target.exists() or target.read_text() != generated:
            raise SystemExit('Generated level data is stale; run make.')
    else:
        target.write_text(generated)

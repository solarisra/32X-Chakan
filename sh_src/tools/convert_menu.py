"""Pack the original menu planes and title sprites for GDL."""
from pathlib import Path
from indexed_png import read_png
from gdl_assets import pack_tiles,pack_spans,native_palette
ROOT=Path(__file__).resolve().parent.parent
def generate():
    out=['/* Generated by convert_menu.py. */']
    def array(kind,name,values):
        out.append(f'static const {kind} menu_{name}[] = {{')
        for i in range(0,len(values),20): out.append(','.join(map(str,values[i:i+20]))+',')
        out.append('};')
    for name,file in [('far','lightning_a'),('close','lightning_b'),('splash','splash_lettering'),('main','lettering'),('options','options_menu_lettering'),('back','bgb')]:
        filename=file if name=='options' else 'main_menu_'+file
        palette=None if name=='back' else []
        w,h,rows,pal=read_png(ROOT/'res/menus'/(filename+'.png'),rgb_palette=palette,embedded_palette=name!='back')
        # Background repeats at a power-of-two tile width; pad the 320px source.
        if name=='back': rows=[row+[0]*(512-w) for row in rows]; w=512
        tiles,tilemap=pack_tiles(rows,name!='back',16 if name=='back' else 0)
        array('uint32_t',name+'_tiles',tiles); array('uint16_t',name+'_map',tilemap)
        out.append(f'#define MENU_{name.upper()}_W {w//8}\n#define MENU_{name.upper()}_H {h//8}')
        array('uint16_t',name+'_palette',native_palette(pal))
        if name=='back': array('uint8_t','back_priority',[255]*((w//8*h//8+7)//8))
    for name in ['C','h','a','k','n','arrow']:
        file='main_menu_arrow.png' if name=='arrow' else 'main_menu_title_sprite_'+name+'.png'
        w,h,rows,pal=read_png(ROOT/'res/sprites/Menus'/file)
        for suffix,values in zip(['rows','spans','pixels'],pack_spans(rows,w,h,[(0,0)],0 if name=='arrow' else 32)):
            array('uint8_t' if suffix=='pixels' else 'uint16_t',name+'_'+suffix,values)
        array('uint16_t',name+'_palette',native_palette(pal))
        out.append(f'static const GdlSpanImage menu_{name}_image={{menu_{name}_rows,menu_{name}_spans,menu_{name}_pixels,{w},{h},1}};')
    return '\n'.join(out)+'\n'
if __name__=='__main__': (ROOT/'res/menu_data.h').write_text(generate())

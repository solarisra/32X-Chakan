#!/usr/bin/env python3
"""Convert the original Terrestrial Earth 1 assets for the SH-2 renderer."""
import argparse
import json
from pathlib import Path
from indexed_png import read_png
from gdl_assets import pack_compact_foreground, pack_tiles, pack_spans, native_palette

ROOT = Path(__file__).resolve().parent.parent


def generate():
    out = ['/* Generated by sh_src/tools/convert_t_earth1.py. */']
    def array(ctype, name, values):
        out.append(f'static const {ctype} earth_{name}[] = {{')
        for i in range(0, len(values), 20):
            out.append(','.join(map(str, values[i:i + 20])) + ',')
        out.append('};')
    w, h, rows, fg_colors = read_png(ROOT / 'res/levels/T_Earth/T_Earth_1_fg.png')
    if (w, h) != (2576, 864):
        raise ValueError('unexpected Earth 1 foreground dimensions')
    tiles, offsets, tilemap = pack_compact_foreground(rows)
    array('uint32_t', 'fg_tiles', tiles)
    array('uint16_t', 'fg_rows', offsets)
    array('uint16_t', 'fg_map', tilemap)
    w, h, rows, bg_colors = read_png(ROOT / 'res/levels/T_Earth/T_Earth_1_bg.png')
    if (w, h) != (256, 224):
        raise ValueError('unexpected Earth 1 background dimensions')
    tiles, tilemap = pack_tiles(rows, False, 16)
    array('uint32_t', 'bg_tiles', tiles)
    array('uint16_t', 'bg_map', tilemap)
    _, _, rows, character_colors = read_png(ROOT / 'res/sprites/Chakan/chakan_anim_no_weapons.png')
    frames = [(0, 0)] + [(f * 112, 80) for f in range(8)] + [(0, a * 80) for a in (2, 3, 4)]
    for name, values in zip(('rows', 'spans', 'pixels'), pack_spans(rows, 112, 80, frames, 32)):
        array('uint8_t' if name == 'pixels' else 'uint16_t', 'chakan_' + name, values)
    colors = native_palette(fg_colors + bg_colors + character_colors)
    for i in (0, 16, 32):
        colors[i] = 0
    array('uint16_t', 'palette', colors)
    _, _, action_rows, _ = read_png(ROOT / 'res/sprites/Chakan/chakan_anim_no_weapons.png')
    actions = [(0, 400)] + [(f * 112, 480) for f in range(4)]
    for suffix, values in zip(('rows', 'spans', 'pixels'), pack_spans(action_rows, 112, 80, actions, 32)):
        array('uint8_t' if suffix == 'pixels' else 'uint16_t', 'actions_' + suffix, values)
    data = json.loads((ROOT / 'src/levels/terrestrial/t_earth1_collision.json').read_text())
    if (data['width'], data['height'], data['cell_size']) != (161, 54, 16):
        raise ValueError('unexpected Earth 1 collision dimensions')
    if len(data['rows_rle']) != 54:
        raise ValueError('Earth 1 collision height mismatch')
    grid = []
    for row in data['rows_rle']:
        cells = []
        for run in row:
            if not isinstance(run, str) or len(run) != 6 or not run.startswith('0x'):
                raise ValueError('collision runs must use hexadecimal strings: 0xTTCC')
            word = int(run, 16)
            tile, count = word >> 8, word & 255
            if tile not in range(10) or not count:
                raise ValueError('invalid Earth 1 collision run')
            cells.extend([tile] * count)
        if len(cells) != 161:
            raise ValueError('Earth 1 collision row width mismatch')
        grid.extend(cells)
    array('uint8_t', 'collision', grid)
    out.extend([f'#define EARTH_SPAWN_X {data["spawn"][0]}', f'#define EARTH_SPAWN_Y {data["spawn"][1]}'])
    return '\n'.join(out) + '\n'


if __name__ == '__main__':
    parser = argparse.ArgumentParser()
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    text = generate()
    target = ROOT / 'res/t_earth1_data.h'
    if args.check:
        if not target.exists() or target.read_text() != text:
            raise SystemExit('Earth 1 resources are stale')
    else:
        target.write_text(text)

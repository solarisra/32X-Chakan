#!/usr/bin/env python3
"""Convert the original Terrestrial Water 1 assets for the SH-2 renderer."""
import argparse
import json
from pathlib import Path
from indexed_png import read_png
from gdl_assets import pack_compact_foreground, pack_compact_background, pack_spans, native_palette

ROOT = Path(__file__).resolve().parent.parent


def priority_bits(rows):
    width = len(rows[0]) // 8
    bits = [0] * ((width * (len(rows)//8) + 7)//8)
    # SGDK adds the TRUE base priority (0x8000) to each map tile attribute.
    # A resource priority bit therefore wraps to low priority in this level.
    for ty in range(len(rows)//8):
        for tx in range(width):
            high = any(v&128 for row in rows[ty*8:ty*8+8] for v in row[tx*8:tx*8+8])
            if not high:
                index = ty*width+tx
                bits[index>>3] |= 1 << (index&7)
    return bits


def generate():
    out = ['/* Generated by sh_src/tools/convert_t_water1.py. */']
    def array(ctype, name, values):
        out.append(f'static const {ctype} water_{name}[] = {{')
        for i in range(0, len(values), 20):
            out.append(','.join(map(str, values[i:i + 20])) + ',')
        out.append('};')
    w, h, rows, fg_colors = read_png(ROOT / 'res/levels/T_Water/T_Water_1_fg_w_prio_new.png',256)
    if (w, h) != (6400, 496):
        raise ValueError('unexpected Water 1 foreground dimensions')
    fg_priority=priority_bits(rows)
    array('uint8_t', 'fg_priority', fg_priority)
    rows = [[v&15 for v in row] for row in rows]
    tiles, offsets, tilemap = pack_compact_foreground(rows)
    if max(tilemap)>=32768:
        raise ValueError('Water foreground directory exceeds tagged map range')
    tilemap=[v|(32768 if fg_priority[i>>3]&(1<<(i&7)) else 0) for i,v in enumerate(tilemap)]
    array('uint32_t', 'fg_tiles', tiles)
    array('uint16_t', 'fg_rows', offsets)
    array('uint16_t', 'fg_map', tilemap)
    w, h, rows, bg_colors = read_png(ROOT / 'res/levels/T_Water/T_Water_1_bg_w_prio.png',256)
    if (w, h) != (512, 496):
        raise ValueError('unexpected Water 1 background dimensions')
    bg_priority = priority_bits(rows)
    array('uint8_t', 'bg_priority', bg_priority)
    opaque_rows = []
    for y, row in enumerate(rows):
        high = all(bg_priority[((y//8)*64+x)>>3] & (1<<(((y//8)*64+x)&7)) for x in range(64))
        opaque_rows.append(int(high and all(v&15 for v in row)))
    array('uint8_t', 'bg_opaque_rows', opaque_rows)
    # Bake priority AND opacity into a spare pixel bit. The renderer can align
    # colors and coverage together instead of looking up two priority tiles and
    # deriving transparent-pixel masks for every eight output pixels.
    rows = [[(v&15) | (128 if v&15 and
             bg_priority[((y//8)*64+x//8)>>3] & (1<<(((y//8)*64+x//8)&7)) else 0)
             for x,v in enumerate(row)] for y,row in enumerate(rows)]
    tiles, offsets, tilemap = pack_compact_background(rows, 16)
    array('uint16_t', 'bg_rows', offsets)
    array('uint32_t', 'bg_tiles', tiles)
    array('uint16_t', 'bg_map', tilemap)
    _, _, rows, character_colors = read_png(ROOT / 'res/sprites/Chakan/chakan_anim_no_weapons.png')
    frames = [(0, 0)] + [(f * 112, 80) for f in range(8)] + [(0, a * 80) for a in (2, 3, 4)]
    for name, values in zip(('rows', 'spans', 'pixels'), pack_spans(rows, 112, 80, frames, 32)):
        array('uint8_t' if name == 'pixels' else 'uint16_t', 'chakan_' + name, values)
    colors = native_palette(fg_colors[:16] + bg_colors[:16] + character_colors)
    for i in (0, 16, 32):
        colors[i] = 0
    array('uint16_t', 'palette', colors)
    _, _, action_rows, _ = read_png(ROOT / 'res/sprites/Chakan/chakan_anim_no_weapons.png')
    actions = [(0, 400)] + [(f * 112, 480) for f in range(4)]
    for suffix, values in zip(('rows', 'spans', 'pixels'), pack_spans(action_rows, 112, 80, actions, 32)):
        array('uint8_t' if suffix == 'pixels' else 'uint16_t', 'actions_' + suffix, values)
    data = json.loads((ROOT / 'src/levels/terrestrial/water/t_water1_collision.json').read_text())
    if (data['width'], data['height'], data['cell_size']) != (400, 31, 16):
        raise ValueError('unexpected Water 1 collision dimensions')
    if len(data['rows_rle']) != 31:
        raise ValueError('Water 1 collision height mismatch')
    grid = []
    for row in data['rows_rle']:
        cells = []
        for run in row:
            if not isinstance(run, str) or len(run) != 6 or not run.startswith('0x'):
                raise ValueError('collision runs must use hexadecimal strings: 0xTTCC')
            word = int(run, 16)
            tile, count = word >> 8, word & 255
            if tile not in range(27) or not count:
                raise ValueError('invalid Water 1 collision run')
            cells.extend([tile] * count)
        if len(cells) != 400:
            raise ValueError('Water 1 collision row width mismatch')
        grid.extend(cells)
    array('uint8_t', 'collision', grid)
    out.extend([f'#define WATER_SPAWN_X {data["spawn"][0]}', f'#define WATER_SPAWN_Y {data["spawn"][1]}'])
    return '\n'.join(out) + '\n'


if __name__ == '__main__':
    parser = argparse.ArgumentParser()
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    text = generate()
    target = ROOT / 'res/t_water1_data.h'
    if args.check:
        if not target.exists() or target.read_text() != text:
            raise SystemExit('Water 1 resources are stale')
    else:
        target.write_text(text)

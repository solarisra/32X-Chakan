"""Pack the five original intro scenes, including the RGB palette header."""
from pathlib import Path
from indexed_png import read_png
from gdl_assets import pack_compact_foreground,pack_compact_background,pack_spans,native_palette
ROOT=Path(__file__).resolve().parent.parent

def scene_pixels(number,plane):
    path=ROOT/'res/intro'/f'intro_{number}_{"text_bga" if plane=="fg" else "bgb"}.png'
    if number==1 and plane=='bg':
        return read_png(path,max_colors=64,rgb_palette=[],embedded_palette=True)
    return read_png(path)

def generate():
    out=['/* Generated by convert_intro.py. */']
    def array(kind,name,values):
        out.append(f'static const {kind} intro_{name}[] = {{')
        for i in range(0,len(values),20): out.append(','.join(map(str,values[i:i+20]))+',')
        out.append('};')
    for number in range(1,6):
        for plane in ('fg','bg'):
            w,h,rows,palette=scene_pixels(number,plane)
            if plane=='fg':
                # Scene 5 text uses PAL1; all other text uses PAL0.
                base=16 if number==5 else 0
                rows=[[v+base if v else 0 for v in row] for row in rows]
                tiles,offsets,tilemap=pack_compact_foreground(rows)
            else:
                rows=[row+[0]*(512-w) for row in rows];w=512
                tiles,offsets,tilemap=pack_compact_background(rows)
            name=f'{number}_{plane}'
            array('uint32_t',name+'_tiles',tiles)
            array('uint16_t',name+'_rows',offsets)
            array('uint16_t',name+'_map',tilemap)
            array('uint16_t',name+'_palette',native_palette(palette))
            out.append(f'static const GdlTilemap intro_{name}={{intro_{name}_tiles,intro_{name}_map,{w//8},{h//8},intro_{name}_rows}};')
    w,h,rows,palette=read_png(ROOT/'res/intro/intro_sprite_indexed.png')
    if (w,h)!=(672,88): raise ValueError('Expected six 112x88 Chakan frames')
    for name,values in zip(('rows','spans','pixels'),pack_spans(rows,112,88,[(i*112,0) for i in range(6)],16)):
        array('uint8_t' if name=='pixels' else 'uint16_t','chakan_'+name,values)
    array('uint16_t','chakan_palette',native_palette(palette))
    out.append('static const GdlSpanImage intro_chakan={intro_chakan_rows,intro_chakan_spans,intro_chakan_pixels,112,88,6};')
    # Linear screen cache: no tile lookups in the frame hot path. Text is a
    # sparse sequence of (word offset, opaque pixels, transparency mask).
    maximum=0
    for number in range(1,6):
        _,_,bg,_=scene_pixels(number,'bg')
        _,_,fg,_=scene_pixels(number,'fg')
        if number in (2,3,4):
            bg=[[fg[y][x] or bg[y][x] for x in range(320)] for y in range(224)]
        words=[sum(row[x+i]<<(24-8*i) for i in range(4)) for row in bg for x in range(0,320,4)]
        array('uint32_t',f'{number}_screen',words)
        offsets,patches=[0],[]
        for row in fg:
            if number not in (2,3,4):
                for x in range(0,320,4):
                    pixels=row[x:x+4]
                    if not any(pixels): continue
                    base=16 if number==5 else 0
                    value=sum((v+base if v else 0)<<(24-8*i) for i,v in enumerate(pixels))
                    mask=sum((0 if v else 255)<<(24-8*i) for i,v in enumerate(pixels))
                    patches.extend((x//4,value,mask))
            offsets.append(len(patches)//3)
        array('uint16_t',f'{number}_patch_rows',offsets)
        array('uint32_t',f'{number}_patches',patches or [0])
        maximum=max(maximum,len(patches))
    out.append(f'#define INTRO_PATCH_WORDS {maximum}')
    _,_,bg,_=scene_pixels(1,'bg')
    animation=[]
    # Word-aligned rectangle around Chakan at (127,55), 112x88 pixels.
    for frame_index in range(6):
        for y in range(88):
            row=bg[y+55][124:244].copy()
            for x,v in enumerate(rows[y][frame_index*112:(frame_index+1)*112]):
                if v: row[x+3]=v+16
            animation.extend(sum(row[x+i]<<(24-8*i) for i in range(4)) for x in range(0,120,4))
    array('uint32_t','animation',animation)
    return '\n'.join(out)+'\n'

if __name__=='__main__': (ROOT/'res/intro_data.h').write_text(generate())

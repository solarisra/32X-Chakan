#!/usr/bin/env python3
"""Convert the original Terrestrial Air 1 assets for the SH-2 renderer."""
import argparse
import json
from pathlib import Path
from indexed_png import read_png
from gdl_assets import pack_compact_foreground, pack_tiles, pack_spans, native_palette

ROOT = Path(__file__).resolve().parent.parent


def generate():
    out = ['/* Generated by sh_src/tools/convert_t_air1.py. */']
    def array(ctype, name, values):
        out.append(f'static const {ctype} air_{name}[] = {{')
        for i in range(0, len(values), 20):
            out.append(','.join(map(str, values[i:i + 20])) + ',')
        out.append('};')
    w, h, rows, fg_colors = read_png(ROOT / 'res/levels/T_Air/T_Air_1_fg.png', 256)
    if (w, h) != (1920, 1440):
        raise ValueError('unexpected Air 1 foreground dimensions')
    priority = [0] * ((240 * 180 + 7) // 8)
    for ty in range(180):
        for tx in range(240):
            if any(v & 128 for row in rows[ty*8:ty*8+8] for v in row[tx*8:tx*8+8]):
                index = ty * 240 + tx
                priority[index >> 3] |= 1 << (index & 7)
    if any(v & 0x60 for row in rows for v in row):
        raise ValueError('unsupported Air palette flags')
    rows = [[(v & 31) if v & 15 else 0 for v in row] for row in rows]
    tiles, offsets, tilemap = pack_compact_foreground(rows)
    array('uint8_t', 'fg_priority', priority)
    array('uint32_t', 'fg_tiles', tiles)
    array('uint16_t', 'fg_rows', offsets)
    array('uint16_t', 'fg_map', tilemap)
    w, h, rows, bg_colors = read_png(ROOT / 'res/levels/T_Air/T_Air_1_bg_wide.png')
    if (w, h) != (256, 224):
        raise ValueError('unexpected Air 1 background dimensions')
    tiles, tilemap = pack_tiles(rows, False, 48)
    array('uint32_t', 'bg_tiles', tiles)
    array('uint16_t', 'bg_map', tilemap)
    _, _, rows, character_colors = read_png(ROOT / 'res/sprites/Chakan/chakan_anim_no_weapons.png')
    frames = [(0, 0)] + [(f * 112, 80) for f in range(8)] + [(0, a * 80) for a in (2, 3, 4)]
    for name, values in zip(('rows', 'spans', 'pixels'), pack_spans(rows, 112, 80, frames, 32)):
        array('uint8_t' if name == 'pixels' else 'uint16_t', 'chakan_' + name, values)
    palettes = []
    for bank in range(2):
        lines = (ROOT / f'res/levels/T_Air/pal_t_air1_fg_pal{bank}.pal').read_text().splitlines()
        if lines[:3] != ['JASC-PAL', '0100', '16']:
            raise ValueError('invalid Air foreground palette')
        for line in lines[3:19]:
            r, g, b = map(int, line.split())
            palettes.append((b >> 5) << 9 | (g >> 5) << 5 | (r >> 5) << 1)
    colors = native_palette(palettes + character_colors + bg_colors)
    for i in (0, 16, 32, 48):
        colors[i] = 0
    array('uint16_t', 'palette', colors)
    _, _, action_rows, _ = read_png(ROOT / 'res/sprites/Chakan/chakan_anim_no_weapons.png')
    actions = [(0, 400)] + [(f * 112, 480) for f in range(4)]
    for suffix, values in zip(('rows', 'spans', 'pixels'), pack_spans(action_rows, 112, 80, actions, 32)):
        array('uint8_t' if suffix == 'pixels' else 'uint16_t', 'actions_' + suffix, values)
    data = json.loads((ROOT / 'src/levels/terrestrial/air/t_air1_collision.json').read_text())
    if (data['width'], data['height'], data['cell_size']) != (120, 90, 16):
        raise ValueError('unexpected Air 1 collision dimensions')
    if len(data['rows_rle']) != 90:
        raise ValueError('Air 1 collision height mismatch')
    grid = []
    for row in data['rows_rle']:
        cells = []
        for run in row:
            if not isinstance(run, str) or len(run) != 6 or not run.startswith('0x'):
                raise ValueError('collision runs must use hexadecimal strings: 0xTTCC')
            word = int(run, 16)
            tile, count = word >> 8, word & 255
            if tile not in range(5) or not count:
                raise ValueError('invalid Air 1 collision run')
            cells.extend([tile] * count)
        if len(cells) != 120:
            raise ValueError('Air 1 collision row width mismatch')
        grid.extend(cells)
    array('uint8_t', 'collision', grid)
    out.extend([f'#define AIR_SPAWN_X {data["spawn"][0]}', f'#define AIR_SPAWN_Y {data["spawn"][1]}'])
    return '\n'.join(out) + '\n'


if __name__ == '__main__':
    parser = argparse.ArgumentParser()
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    text = generate()
    target = ROOT / 'res/t_air1_data.h'
    if args.check:
        if not target.exists() or target.read_text() != text:
            raise SystemExit('Air 1 resources are stale')
    else:
        target.write_text(text)

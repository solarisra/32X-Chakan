"""Convert original logo pixels/palettes without changing their sprite origin."""
from pathlib import Path
from indexed_png import read_png
from gdl_assets import pack_spans,native_palette,pack_compact_foreground
ROOT=Path(__file__).resolve().parent.parent
def generate():
    out=['/* Generated by convert_logo.py. */']
    def array(kind,name,values):
        out.append(f'static const {kind} logo_{name}[] = {{')
        for i in range(0,len(values),20): out.append(','.join(map(str,values[i:i+20]))+',')
        out.append('};')
    w,h,rows,blue=read_png(ROOT/'res/sgdk_retro_logo.png')
    rw,rh,_,red=read_png(ROOT/'res/sgdk_retro_logo_red.png')
    if (w,h,rw,rh)!=(96,32,96,32):
        raise ValueError('Expected original 96x32 logo assets')
    # Source changes only the palette; red image pixels are not displayed.
    for name,values in zip(('rows','spans','pixels'),pack_spans(rows,96,32,[(0,0)])):
        array('uint8_t' if name=='pixels' else 'uint16_t',name,values)
    array('uint16_t','blue',native_palette(blue))
    array('uint16_t','red',native_palette(red))
    tiles,offsets,tilemap=pack_compact_foreground([[0]*320 for _ in range(224)])
    array('uint32_t','empty_tiles',tiles)
    array('uint16_t','empty_rows',offsets)
    array('uint16_t','empty_map',tilemap)
    array('uint32_t','black_tiles',[0]*16)
    array('uint16_t','black_map',[0])
    return '\n'.join(out)+'\n'
if __name__=='__main__': (ROOT/'res/logo_data.h').write_text(generate())

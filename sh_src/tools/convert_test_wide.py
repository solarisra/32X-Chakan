#!/usr/bin/env python3
"""32X indexed tiles/maps and full animation frames, from original PNGs."""
import argparse
import json
from pathlib import Path
from indexed_png import read_png
ROOT = Path(__file__).resolve().parent.parent


def convert_image(path):
    width, height, rows, palette = read_png(path)
    tiles, lookup, tilemap = [], {}, []
    for y in range(0, height, 8):
        for x in range(0, width, 8):
            tile = tuple(rows[y + dy][x + dx] for dy in range(8) for dx in range(8))
            if tile not in lookup:
                lookup[tile] = len(tiles)
                tiles.append(tile)
            tilemap.append(lookup[tile])
    return width, height, rows, palette, tiles, tilemap


def generate():
    out = ['/* Generated by sh_src/tools/convert_test_wide.py. */']
    def array(ctype, name, values, per_line=20):
        out.append(f'static const {ctype} {name}[] = {{')
        for i in range(0, len(values), per_line):
            out.append(','.join(map(str, values[i:i + per_line])) + ',')
        out.append('};')
    colors = []
    for name, filename, size in [('wide_fg', 'fg_test_level_wide.png', (1440, 240)),
                                  ('wide_bg', 'portal_starfield.png', (512, 256))]:
        w, h, rows, palette, tiles, tilemap = convert_image(ROOT / 'res/levels/Hub' / filename)
        if (w, h) != size:
            raise ValueError('unexpected map dimensions')
        packed = []
        for tile in tiles:
            for y in range(8):
                pixels = tile[y * 8:y * 8 + 8]
                words = [sum((v + (16 if name == 'wide_bg' else 0)) << (24 - i * 8)
                             for i, v in enumerate(pixels[start:start + 4])) for start in (0, 4)]
                packed.extend(words)
                if name == 'wide_fg':
                    masks = [sum((255 if v == 0 else 0) << (24 - i * 8)
                                 for i, v in enumerate(pixels[start:start + 4])) for start in (0, 4)]
                    kind = 0 if not any(pixels) else 1 if all(pixels) else 2
                    packed.extend([*masks, kind])
        array('uint32_t', name + '_tiles', packed)
        stride = 40 if name == 'wide_fg' else 16
        if len(tiles) * stride > 65536:
            raise ValueError('packed tile offsets exceed 16-bit map entries')
        array('uint16_t', name + '_map', [tile * stride for tile in tilemap])
        colors.extend(palette)
    w, h, rows, palette = read_png(ROOT / 'res/sprites/Chakan/chakan_anim_no_weapons.png')
    if (w, h) != (896, 400):
        raise ValueError('unexpected Chakan sheet dimensions')
    span_rows, spans, span_pixels = [0], [], []
    # Each row has a range of opaque runs. Store both facings to avoid runtime
    # transparent-pixel tests, palette addition and sprite reversal.
    for flip in (False, True):
        for a in range(5):
            for f in range(8 if a == 1 else 1):
                for y in range(80):
                    row = rows[a * 80 + y][f * 112:(f + 1) * 112]
                    if flip:
                        row = row[::-1]
                    x = 0
                    while x < 112:
                        if not row[x]:
                            x += 1
                            continue
                        start = x
                        while x < 112 and row[x]:
                            x += 1
                        spans.extend([start, x - start, len(span_pixels)])
                        span_pixels.extend(v + 32 for v in row[start:x])
                    span_rows.append(len(spans) // 3)
    if len(span_pixels) > 65535 or len(spans) // 3 > 65535:
        raise ValueError('sprite spans exceed 16-bit offsets')
    array('uint16_t', 'wide_sprite_rows', span_rows)
    array('uint16_t', 'wide_sprite_spans', spans)
    array('uint8_t', 'wide_sprite_pixels', span_pixels)
    colors.extend(palette)
    # Expand original Genesis channel bits to native 32X 5:5:5 channels.
    rgb = []
    for c in colors:
        r, g, b = (c >> 1) & 7, (c >> 5) & 7, (c >> 9) & 7
        rgb.append((r * 31 // 7) | ((g * 31 // 7) << 5) | ((b * 31 // 7) << 10))
    array('uint16_t', 'wide_palette', rgb)
    collision = json.loads((ROOT / 'src/levels/test/test_wide_collision.json').read_text())
    if (collision['width'], collision['height'], collision['cell_size']) != (90, 15, 16):
        raise ValueError('unexpected collision dimensions')
    grid = []
    for row in collision['rows_rle']:
        cells = []
        for encoded_run in row:
            if not isinstance(encoded_run, str) or len(encoded_run) != 6 or not encoded_run.startswith("0x"):
                raise ValueError("collision runs must use four-digit hexadecimal strings: 0xTTCC")
            run = int(encoded_run, 16)
            tile, count = run >> 8, run & 255
            if tile not in (0, 1) or count == 0:
                raise ValueError('unsupported collision run')
            cells.extend([tile] * count)
        if len(cells) != 90:
            raise ValueError('collision width mismatch')
        grid.extend(cells)
    if len(grid) != 90 * 15:
        raise ValueError('collision height mismatch')
    array('uint8_t', 'wide_collision', grid)
    out.extend([f'#define WIDE_SPAWN_X {collision["spawn"][0]}',
                f'#define WIDE_SPAWN_Y {collision["spawn"][1]}'])
    return '\n'.join(out) + '\n'


if __name__ == '__main__':
    parser = argparse.ArgumentParser()
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    output = generate()
    target = ROOT / 'res/test_wide_data.h'
    if args.check:
        if not target.exists() or target.read_text() != output:
            raise SystemExit('TEST_WIDE resources are stale')
    else:
        target.write_text(output)
